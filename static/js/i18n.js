const TABLE = { pl: PL, en: EN };

function detectInitial() {
  try {
    const saved = localStorage.getItem("muzart_lang");
    if (saved && TABLE[saved]) return saved;
  } catch (_) { /* ignore */ }
  return "pl"; // Domyślnie polski — tak jak w aplikacji Android.
}

export const i18n = new (class extends Emitter {
  constructor() {
    super();
    this.lang = detectInitial();
  }
  setLanguage(code) {
    if (!TABLE[code] || code === this.lang) return;
    this.lang = code;
    try { localStorage.setItem("muzart_lang", code); } catch (_) { /* ignore */ }
    document.documentElement.lang = code;
    this.emit("change", code);
  }
})();

export function t(key, params) {
  let s = TABLE[i18n.lang]?.[key] ?? PL[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
